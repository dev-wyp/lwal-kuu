interface I18nContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (text: string, values?: TranslationValues) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    try {
      return localStorage.getItem('shopflow_language') === 'my' ? 'my' : 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = useCallback((next: AppLanguage) => {
    setLanguageState(next);
    try { localStorage.setItem('shopflow_language', next); } catch { /* storage may be unavailable */ }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === 'my' ? 'my' : 'en';
    document.documentElement.dataset.language = language;
  }, [language]);

  const t = useCallback((text: string, values?: TranslationValues) => {
    let translated = language === 'my' ? (myTranslations[text] ?? text) : text;
    if (values) {
      for (const [key, value] of Object.entries(values)) translated = translated.split(`{{${key}}}`).join(String(value));
    }
    return translated;
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = (): I18nContextValue => {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used within I18nProvider');
  return value;
};
